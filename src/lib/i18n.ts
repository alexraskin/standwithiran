export function pageHref(lang: Lang, page: Page): string {
  return localePath(lang) + (page ? `${page}/` : '');
}

/** getStaticPaths for a `[...locale]` route: `/x/` in English, `/fa/x/` in Farsi. */
export function localeStaticPaths() {
  return [
    { params: { locale: undefined }, props: { lang: 'en' as Lang } },
    { params: { locale: 'fa' }, props: { lang: 'fa' as Lang } },
  ];
}

/** Persian digits for Farsi pages; years and ranges are stored with ASCII digits. */
export function localizeDigits(value: string, lang: Lang): string {
  return lang === 'fa' ? value.replace(/\d/g, (d) => '۰۱۲۳۴۵۶۷۸۹'[Number(d)]) : value;
}

/**
 * Formats an ISO `YYYY-MM-DD` config date for display.
 *
 * Anything that is not an ISO date is passed through untouched.
 *
 * Farsi is formatted on the Gregorian calendar (`-u-ca-gregory`), matching what
 * the page showed before. Dropping that subtag would switch it to the Persian
 * calendar, which is a content decision, not a formatting one.
 */
export function formatDate(value: string, lang: Lang): string {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value)) return value;

  const parsed = new Date(`${value}T00:00:00Z`);
  if (Number.isNaN(parsed.getTime())) return value;

  // UTC throughout: formatting a UTC midnight in a behind-UTC zone rolls the
  // date back a day.
  return new Intl.DateTimeFormat(lang === 'fa' ? 'fa-IR-u-ca-gregory' : 'en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    timeZone: 'UTC',
  }).format(parsed);
}
